create table if not exists public.order_events (
  id bigint generated by default as identity primary key,
  order_id text not null references public.orders(order_id) on delete cascade,
  created_at timestamptz not null default now(),
  event_type text not null,
  actor text not null default 'system',
  metadata jsonb not null default '{}'::jsonb
);
create index if not exists order_events_order_created_idx on public.order_events (order_id, created_at desc);

create table if not exists public.order_files (
  id bigint generated by default as identity primary key,
  order_id text not null references public.orders(order_id) on delete cascade,
  created_at timestamptz not null default now(),
  kind text not null,
  bucket text not null,
  path text not null,
  mime_type text,
  byte_size bigint,
  original_name text,
  metadata jsonb not null default '{}'::jsonb,
  unique(bucket, path)
);
create index if not exists order_files_order_idx on public.order_files (order_id, created_at desc);

