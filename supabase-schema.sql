create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_id text unique not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  submitted_at timestamptz,
  paid_at timestamptz,
  status text not null default 'pending_payment',
  payment_status text not null default 'unpaid',
  fulfillment_status text not null default 'not_started',
  product text not null,
  region text not null default 'US',
  language text not null default 'en',
  currency text not null,
  total numeric not null,
  addons jsonb not null default '[]'::jsonb,
  customer_name text,
  customer_email text not null,
  customer_phone text,
  brief jsonb not null,
  source jsonb not null default '{}'::jsonb,
  client_request_id text unique,
  coupon_code text,
  coupon_discount numeric not null default 0,
  detected_country text,
  region_override boolean not null default false,
  region_verification_required boolean not null default false,
  terms_accepted boolean not null default false,
  privacy_accepted boolean not null default false,
  materials_accepted boolean not null default false,
  terms_version text,
  privacy_version text,
  accepted_at timestamptz,
  acceptance_evidence jsonb not null default '{}'::jsonb,
  payment_provider text,
  stripe_session_id text unique,
  stripe_payment_intent_id text,
  stripe_customer_id text,
  cover_bucket text,
  cover_path text,
  cover_uploaded_at timestamptz,
  admin_notified_at timestamptz,
  customer_paid_email_at timestamptz
);

